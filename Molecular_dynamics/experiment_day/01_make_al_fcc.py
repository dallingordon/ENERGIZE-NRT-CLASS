#!/usr/bin/env python3
"""
Create a 3x3x3 conventional FCC Al crystal for the LAMMPS class exercise.

Outputs
-------
al_fcc_3x3x3.data : LAMMPS data file (atom_style atomic)
al_fcc_3x3x3.xyz  : simple XYZ file for visualization

No external Python packages are required.
"""

from pathlib import Path

# -----------------------------
# User-adjustable settings
# -----------------------------
A0 = 4.05       # FCC lattice parameter, Angstrom. face center cubic.  a cubic crystal. 
NX = NY = NZ = 3
MASS_AL = 26.9815385

OUTDIR = Path(__file__).resolve().parent
DATA_FILE = OUTDIR / "al_fcc_3x3x3.data"
XYZ_FILE = OUTDIR / "al_fcc_3x3x3.xyz"

# Conventional FCC basis in fractional coordinates.
basis = [
    (0.0, 0.0, 0.0),
    (0.0, 0.5, 0.5),
    (0.5, 0.0, 0.5),
    (0.5, 0.5, 0.0),
]

atoms = []
atom_id = 1
for i in range(NX):
    for j in range(NY):
        for k in range(NZ):
            for bx, by, bz in basis:
                x = (i + bx) * A0
                y = (j + by) * A0
                z = (k + bz) * A0
                atoms.append((atom_id, 1, x, y, z))
                atom_id += 1

lx, ly, lz = NX * A0, NY * A0, NZ * A0

with DATA_FILE.open("w") as f:
    f.write("3x3x3 conventional FCC Al crystal generated by 01_make_al_fcc.py\n\n")
    f.write(f"{len(atoms)} atoms\n")
    f.write("1 atom types\n\n")
    f.write(f"0.0 {lx:.10f} xlo xhi\n")
    f.write(f"0.0 {ly:.10f} ylo yhi\n")
    f.write(f"0.0 {lz:.10f} zlo zhi\n\n")
    f.write("Masses\n\n")
    f.write(f"1 {MASS_AL:.10f}\n\n")
    f.write("Atoms # atomic\n\n")
    for aid, atype, x, y, z in atoms:
        f.write(f"{aid:d} {atype:d} {x:.10f} {y:.10f} {z:.10f}\n")

with XYZ_FILE.open("w") as f:
    f.write(f"{len(atoms)}\n")
    f.write(f"FCC Al {NX}x{NY}x{NZ}, a0={A0:.4f} A\n")
    for _, _, x, y, z in atoms:
        f.write(f"Al {x:.10f} {y:.10f} {z:.10f}\n")

print("Created FCC Al structure")
print(f"  lattice parameter : {A0:.4f} A")
print(f"  replication       : {NX} x {NY} x {NZ}")
print(f"  number of atoms   : {len(atoms)}")
print(f"  box dimensions    : {lx:.4f} x {ly:.4f} x {lz:.4f} A")
print(f"  LAMMPS data       : {DATA_FILE.name}")
print(f"  XYZ               : {XYZ_FILE.name}")
